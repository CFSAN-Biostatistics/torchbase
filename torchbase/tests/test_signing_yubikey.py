class TestYubiKeyCidSigning:
    def test_sign_and_verify_cid(self, yubikey_signer):
        from torchbase.signing import sign_cid, verify_cid, _b64u
        cid = "QmHardwareTest123abc"
        namespace = "examples"
        version = "1.0.0"
        pub_b64 = _b64u(yubikey_signer.public_key_bytes())

        sig = sign_cid(cid, namespace, version, yubikey_signer)
        assert verify_cid(cid, namespace, version, sig, pub_b64, yubikey_signer.algorithm)

    def test_cid_sig_wrong_cid_fails(self, yubikey_signer):
        from torchbase.signing import sign_cid, verify_cid, _b64u
        pub_b64 = _b64u(yubikey_signer.public_key_bytes())
        sig = sign_cid("QmReal", "examples", "1.0.0", yubikey_signer)
        assert not verify_cid("QmFake", "examples", "1.0.0", sig, pub_b64, yubikey_signer.algorithm)


