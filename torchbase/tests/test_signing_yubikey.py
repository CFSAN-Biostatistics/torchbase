class TestYubiKeySignerInit:
    def test_import(self):
        """ykman package must be importable."""
        from torchbase.signing import YubiKeySigner
        assert YubiKeySigner is not None

    def test_instantiation_connects(self, yubikey_signer):
        """Constructor must succeed — device is present and accessible."""
        from torchbase.signing import YubiKeySigner
        assert isinstance(yubikey_signer, YubiKeySigner)

    def test_algorithm_detected(self, yubikey_signer):
        """Algorithm must be one of the supported values."""
        assert yubikey_signer.algorithm in ("ed25519", "p256")

    def test_missing_ykman_raises_import_error(self, monkeypatch):
        """If ykman is not available, __init__ raises ImportError (not crashes)."""
        import builtins
        real_import = builtins.__import__

        def _block_ykman(name, *args, **kwargs):
            if name in ("ykman.device", "yubikit.piv"):
                raise ImportError("blocked for test")
            return real_import(name, *args, **kwargs)

        monkeypatch.setattr(builtins, "__import__", _block_ykman)

        from torchbase.signing import YubiKeySigner
        with pytest.raises(ImportError, match="yubikey-manager"):
            YubiKeySigner(slot=SLOT, pin=PIN)


