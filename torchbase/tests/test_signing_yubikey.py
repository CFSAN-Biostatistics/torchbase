class TestYubiKeyTorchSigning:
    def test_sign_torch_creates_signature_toml(self, yubikey_signer, tmp_path):
        from torchbase.signing import sign_torch
        torch_dir = _make_torch(tmp_path)
        sig_path = sign_torch(torch_dir, yubikey_signer)
        assert sig_path.exists()

        import toml
        data = toml.load(sig_path)
        assert "signature" in data
        assert data["signature"]["algorithm"] == yubikey_signer.algorithm

    def test_verify_torch_with_hardware_signature(self, yubikey_signer, tmp_path):
        from torchbase.signing import sign_torch, verify_torch
        torch_dir = _make_torch(tmp_path)
        sign_torch(torch_dir, yubikey_signer)

        from torchbase.signing import _b64u
        pub_b64 = _b64u(yubikey_signer.public_key_bytes())
        result = verify_torch(torch_dir, public_key_b64=pub_b64)
        assert result.valid, f"Verification failed: {result.message}"

    def test_verify_torch_embedded_key(self, yubikey_signer, tmp_path):
        """Embedded public_key in signature.toml is sufficient for verification."""
        from torchbase.signing import sign_torch, verify_torch
        torch_dir = _make_torch(tmp_path)
        sign_torch(torch_dir, yubikey_signer)
        result = verify_torch(torch_dir)
        assert result.valid, f"Verification failed: {result.message}"

    def test_tampered_torch_fails_verification(self, yubikey_signer, tmp_path):
        from torchbase.signing import sign_torch, verify_torch
        torch_dir = _make_torch(tmp_path)
        sign_torch(torch_dir, yubikey_signer)
        (torch_dir / "profiles.tsv").open("a").write("\ntamper\n")

        from torchbase.signing import _b64u
        pub_b64 = _b64u(yubikey_signer.public_key_bytes())
        result = verify_torch(torch_dir, public_key_b64=pub_b64)
        assert not result.valid


