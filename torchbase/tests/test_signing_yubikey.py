"""Hardware tests for YubiKey signing path.

These tests REQUIRE a physical YubiKey with a PIV application.  They are
marked ``hardware`` and excluded from the default pytest run.  Run them with::

    pytest -m hardware -v

or for a specific slot/PIN::

    YUBIKEY_SLOT=9c YUBIKEY_PIN=123456 pytest -m hardware -v

Expected device state
---------------------
- YubiKey plugged in and visible to pcscd
- PIV slot 9c (SIGNATURE) contains a key — either pre-existing or freshly
  generated by the ``test_setup_yubikey_slot`` test
- pcscd running: ``sudo systemctl start pcscd``

Under WSL2
----------
USB passthrough via usbipd-win is required; see BUILDING.md.

Failure modes
-------------
- ``ImportError`` — yubikey-manager not installed: ``pip install 'torchbase[yubikey]'``
- ``DeviceNotFoundError`` — no YubiKey detected (pcscd not running, device
  not attached, or usbipd attachment dropped)
- ``ApduError`` / ``InvalidPinError`` — wrong PIN or slot has no key
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

import pytest

# ---------------------------------------------------------------------------
# Marker — all tests in this file require physical hardware
# ---------------------------------------------------------------------------

pytestmark = pytest.mark.hardware

REPO_ROOT = Path(__file__).parent.parent.parent
EXAMPLE_TORCH = REPO_ROOT / "examples" / "simple_mlst" / "1.0.0.torch"

SLOT = os.environ.get("YUBIKEY_SLOT", "9c")
PIN  = os.environ.get("YUBIKEY_PIN", "123456")


def _make_torch(tmp_path: Path) -> Path:
    torch_dir = tmp_path / "examples" / "simple_mlst" / "1.0.0.torch"
    shutil.copytree(EXAMPLE_TORCH, torch_dir)
    return torch_dir


