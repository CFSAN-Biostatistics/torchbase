class TestYubiKeySigning:
    def test_sign_returns_bytes(self, yubikey_signer):
        sig = yubikey_signer.sign(b"test message")
        assert isinstance(sig, bytes)
        assert len(sig) > 0

    def test_sign_is_deterministic_ed25519(self, yubikey_signer):
        """Ed25519 signatures are deterministic; same message → same sig."""
        if yubikey_signer.algorithm != "ed25519":
            pytest.skip("determinism test only applies to Ed25519")
        msg = b"determinism check"
        sig1 = yubikey_signer.sign(msg)
        sig2 = yubikey_signer.sign(msg)
        assert sig1 == sig2

    def test_sign_different_messages_differ(self, yubikey_signer):
        sig1 = yubikey_signer.sign(b"message one")
        sig2 = yubikey_signer.sign(b"message two")
        assert sig1 != sig2

    def test_signature_verifies(self, yubikey_signer):
        """Signature produced by the device must verify against its public key."""
        from torchbase.signing import _verify_signature, _b64u
        msg = b"hardware verification test"
        sig = yubikey_signer.sign(msg)
        pub = yubikey_signer.public_key_bytes()
        # Should not raise
        _verify_signature(msg, sig, pub, yubikey_signer.algorithm)

    def test_signature_fails_with_wrong_key(self, yubikey_signer, tmp_path):
        """Signature from YubiKey must not verify against a different key."""
        from torchbase.signing import (
            _verify_signature, generate_software_keypair, FileKeySigner, _b64u_decode
        )
        msg = b"wrong key test"
        sig = yubikey_signer.sign(msg)

        priv, pub = generate_software_keypair("other", tmp_path)
        wrong_pub_raw = _b64u_decode(pub.read_text().strip())

        with pytest.raises(Exception):
            _verify_signature(msg, sig, wrong_pub_raw, "ed25519")


