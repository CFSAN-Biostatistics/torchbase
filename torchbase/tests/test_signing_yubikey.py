class TestYubiKeyPublicKey:
    def test_public_key_bytes_returns_bytes(self, yubikey_signer):
        pub = yubikey_signer.public_key_bytes()
        assert isinstance(pub, bytes)
        assert len(pub) > 0

    def test_public_key_length_matches_algorithm(self, yubikey_signer):
        pub = yubikey_signer.public_key_bytes()
        if yubikey_signer.algorithm == "ed25519":
            assert len(pub) == 32, "Ed25519 public key must be 32 bytes"
        elif yubikey_signer.algorithm == "p256":
            assert len(pub) == 65, "P-256 uncompressed point must be 65 bytes (04 || x || y)"

    def test_public_key_is_base64url_encodable(self, yubikey_signer):
        from torchbase.signing import _b64u, _b64u_decode
        pub = yubikey_signer.public_key_bytes()
        encoded = _b64u(pub)
        assert _b64u_decode(encoded) == pub


