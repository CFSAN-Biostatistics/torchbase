class TestSetupYubiKeySlot:
    def test_generates_key_and_writes_pub(self, tmp_path):
        """Generating a key on the device writes a .pub file."""
        from torchbase.signing import setup_yubikey_slot, _b64u_decode
        pub_path = setup_yubikey_slot(SLOT, "testns", tmp_path, pin=PIN)
        assert pub_path.exists()
        raw = _b64u_decode(pub_path.read_text().strip())
        # P-256 uncompressed point is 65 bytes; Ed25519 raw key is 32 bytes
        assert len(raw) in (32, 65)
