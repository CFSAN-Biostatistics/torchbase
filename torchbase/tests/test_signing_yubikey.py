class TestPivSlot:
    def test_all_slots_resolve(self):
        """_piv_slot must resolve all four canonical slot strings."""
        # Import ykman so we get the real SLOT constants, not a stub
        from yubikit.piv import SLOT
        from torchbase.signing import _piv_slot
        assert _piv_slot("9a") == SLOT.AUTHENTICATION
        assert _piv_slot("9c") == SLOT.SIGNATURE
        assert _piv_slot("9d") == SLOT.KEY_MANAGEMENT
        assert _piv_slot("9e") == SLOT.CARD_AUTH

    def test_unknown_slot_raises(self):
        from torchbase.signing import _piv_slot
        with pytest.raises(KeyError):
            _piv_slot("ff")


