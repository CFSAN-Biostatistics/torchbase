@pytest.fixture(scope="module")
def yubikey_signer():
    """Return a YubiKeySigner for the configured slot.

    Fails immediately (not skipped) if ykman is missing or the device is absent.
    """
    from torchbase.signing import YubiKeySigner
    return YubiKeySigner(slot=SLOT, pin=PIN)


